export function kitParts(type, size) {
  const def = DEFS[type];
  const base = KITS[type]?.size;
  if (!def || !base) return [];
  const k = [size[0] / base[0], size[1] / base[1], size[2] / base[2]];
  return def.map((p) => ({
    shape: p.shape,
    c: [p.c[0] * k[0], p.c[1] * k[1], p.c[2] * k[2]],
    s: [p.s[0] * k[0], p.s[1] * k[1], p.s[2] * k[2]],
    r: p.r || [0, 0, 0],
  }));
}

